"""The replication pages' generated parts must equal the check.

Contract L: one home per fact. The marks live in REPLICATION_CHECK.md and the
pages quote them only through blocks generated by scripts/docs_sync.py, so a
regenerated check cannot leave README.md, COVERAGE.md or outputs/README.md
quoting a stale score. These tests recompute the generated parts from the
committed check - with the same functions the generator uses - and fail when
either side drifts.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPLICATION = ROOT / "report" / "replication"

_spec = importlib.util.spec_from_file_location("docs_sync", ROOT / "scripts" / "docs_sync.py")
docs_sync = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(docs_sync)


def _check() -> dict:
    return docs_sync.read_check()


def test_the_stamp_line_matches_the_check():
    lines = (REPLICATION / "README.md").read_text(encoding="utf-8").splitlines()
    markers = [i for i, line in enumerate(lines)
               if line.startswith("<!-- stamp:")
               and "generated from REPLICATION_CHECK.md" in line]
    assert markers, "README.md has no stamp marker"
    stamp = lines[markers[0] + 1]
    assert stamp == docs_sync._stamp_lines(_check()) + "; how it is counted and its history are in"


def test_readme_exhibit_columns_match_the_check():
    check = _check()
    lines = (REPLICATION / "README.md").read_text(encoding="utf-8").splitlines()
    seen = set()
    for line in lines:
        stripped = line.strip()
        if not (stripped.startswith("|") and " | " in stripped):
            continue
        label = stripped.split("|")[1].strip()
        if label in docs_sync.EXHIBIT_TO_BLOCK:
            block = docs_sync.EXHIBIT_TO_BLOCK[label]
            cells = line.split("|")
            assert cells[3].strip() == docs_sync.exhibit_cell(check["blocks"][block]), (
                f"README.md's {label!r} row quotes {cells[3].strip()!r}; the check says "
                f"{docs_sync.exhibit_cell(check['blocks'][block])!r}. Run scripts/docs_sync.py.")
            seen.add(label)
    assert seen == set(docs_sync.EXHIBIT_TO_BLOCK), (
        f"README.md's exhibit table is missing rows: {sorted(set(docs_sync.EXHIBIT_TO_BLOCK) - seen)}")


def test_coverage_scored_column_matches_the_check():
    check = _check()
    lines = (REPLICATION / "COVERAGE.md").read_text(encoding="utf-8").splitlines()
    seen = set()
    for line in lines:
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        label = stripped.split("|")[1].strip()
        if label in docs_sync.COVERAGE_TO_BLOCK:
            block = docs_sync.COVERAGE_TO_BLOCK[label]
            if block is None:
                continue
            cells = line.split("|")
            scored = re.match(r"^(\d+)", cells[3].strip())
            assert scored, f"COVERAGE.md's {label!r} scored cell has no leading count"
            assert int(scored.group(1)) == check["blocks"][block]["cells"], (
                f"COVERAGE.md's {label!r} row scores {scored.group(1)}; the check says "
                f"{check['blocks'][block]['cells']:.0f}. Run scripts/docs_sync.py.")
            seen.add(label)
    assert seen == {k for k, v in docs_sync.COVERAGE_TO_BLOCK.items() if v is not None}


def test_outputs_stamp_matches_the_check():
    readme = REPLICATION / "outputs" / "README.md"
    check = _check()
    pattern = re.compile(r"^One run over the full 474-cohort cache \(score ([0-9.]+) of (\d+)\)")
    stamps = [m for line in readme.read_text(encoding="utf-8").splitlines()
              if (m := pattern.match(line))]
    assert stamps, "outputs/README.md has no stamp line"
    assert float(stamps[0].group(1)) == check["score"]
    assert int(stamps[0].group(2)) == check["total"]


def test_docs_sync_is_idempotent(tmp_path):
    """Running the generator over the committed pages changes nothing."""
    import shutil

    copy = tmp_path / "replication"
    shutil.copytree(REPLICATION, copy)
    sys.modules.pop("docs_sync", None)
    spec = importlib.util.spec_from_file_location("docs_sync_copy", ROOT / "scripts" / "docs_sync.py")
    mod = importlib.util.module_from_spec(spec)
    mod.REPLICATION = copy
    mod.CHECK = copy / "REPLICATION_CHECK.md"
    mod.README = copy / "README.md"
    mod.COVERAGE = copy / "COVERAGE.md"
    mod.OUTPUTS = copy / "outputs"
    spec.loader.exec_module(mod)
    check = mod.read_check()
    mod.sync_readme(check)
    mod.sync_coverage(check)
    mod.sync_outputs(check)
    for name in ("README.md", "COVERAGE.md", "outputs/README.md"):
        assert (copy / name).read_text(encoding="utf-8") == (REPLICATION / name).read_text(
            encoding="utf-8"), f"docs_sync would rewrite {name}; run it and commit the result"
